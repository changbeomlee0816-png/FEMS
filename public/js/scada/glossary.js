  /** 검색 — 해설 탭의 한 줄 검색창용 */
  function search(q) {
    const k = String(q || '').trim().toLowerCase();
    if (!k) return null;
    const hit = (s) => String(s || '').toLowerCase().indexOf(k) >= 0;
    // 이름·약어가 맞는 것을 먼저 보여 준다 (본문에만 언급된 것은 뒤로)
    const score = (id) => {
      const s = SYMBOLS[id];
      if (id.toLowerCase() === k) return 0;
      if (hit(s.name) || hit(s.en)) return 1;
      if (hit(id)) return 2;
      return 3;
    };
    return {
      symbols: Object.keys(SYMBOLS)
        .filter((id) => {
          const s = SYMBOLS[id];
          return hit(id) || hit(s.name) || hit(s.en) || hit(s.what) || hit(s.read) || hit(s.note);
        })
        .sort((a, b) => score(a) - score(b)),
      ansi: ANSI.filter((a) => hit(a.code) || hit(a.name) || hit(a.desc)),
      energy: ENERGY.filter((e) => hit(e.name) || hit(e.what) || hit(e.note)),
      notation: NOTATION.filter((n) => hit(n.term) || hit(n.what)),
    };
  }

  return { SYMBOLS, ENERGY, ANSI, NOTATION, bySymbol, search };
